/**
 * seedJob.groovy: Job DSL script that turns jenkins/seed/repos.yaml into Jenkins jobs.
 *
 * Run by the "seed-job" pipeline (defined in jenkins/casc/jenkins.yaml), which
 * parses the YAML with readYaml and passes it in as the `reposConfig` variable.
 *
 * For each repo it creates (or updates) a Multibranch Pipeline that:
 *   - discovers the branches/PRs matching `branches`
 *   - builds each one with the repo's Jenkinsfile
 *   - is triggered by the GitHub webhook, with a daily branch re-scan as fallback
 *   - carries the repo's `pipeline:` section as a folder property (PIPELINE_CONFIG),
 *     which standardPipeline reads at build time
 * Repos removed from the YAML get their job disabled (not deleted, so history is kept).
 */
import groovy.json.JsonOutput

if (!binding.hasVariable('reposConfig')) {
    throw new IllegalArgumentException('seedJob.groovy expects a `reposConfig` variable (parsed repos.yaml) from the seed job.')
}

List repos = (reposConfig?.repos ?: []) as List
if (repos.isEmpty()) {
    throw new IllegalArgumentException('jenkins/seed/repos.yaml defines no repos under `repos:`.')
}

// Validate everything first, then create jobs: a bad entry must not leave a half-applied state.
List<String> errors = []
repos.eachWithIndex { repo, i -> errors.addAll(validateRepo(repo, i)) }
if (errors) {
    throw new IllegalArgumentException("jenkins/seed/repos.yaml is invalid:\n" + errors.collect { " - ${it}" }.join('\n'))
}

repos.each { Map repo ->
    createMultibranchJob(repo)
    println "Seeded job '${repo.name}' (${repo.source.type})"
}

// ---------------------------------------------------------------------------

List<String> validateRepo(Object repo, int index) {
    String where = "repos[${index}]"
    if (!(repo instanceof Map)) {
        return ["${where} must be a map".toString()]
    }
    List<String> problems = []
    if (!(repo.name ==~ /[A-Za-z0-9._-]+/)) {
        problems << "${where}.name '${repo.name}' must use only letters, digits, '.', '_' or '-'".toString()
    }
    Map source = repo.source instanceof Map ? repo.source : [:]
    switch (source.type) {
        case 'github':
            ['owner', 'repository', 'credentialsId'].each { key ->
                if (!source[key]) problems << "${where}.source.${key} is required for type github".toString()
            }
            if (source.owner == 'replace-me') {
                problems << "${where}.source.owner is still 'replace-me': put your GitHub username in jenkins/seed/repos.yaml".toString()
            }
            break
        case 'git':
            if (!source.remote) problems << "${where}.source.remote is required for type git".toString()
            break
        default:
            problems << "${where}.source.type must be 'github' or 'git', got '${source.type}'".toString()
    }
    if (repo.pipeline != null && !(repo.pipeline instanceof Map)) {
        problems << "${where}.pipeline must be a map of standardPipeline settings".toString()
    }
    return problems
}

void createMultibranchJob(Map repo) {
    Map scm = repo.source   // not named "source": that would hide the Job DSL source { } block
    String branchFilter = repo.branches ?: 'main develop feature/* PR-*'
    String pipelineConfig = JsonOutput.toJson(repo.pipeline ?: [:])

    multibranchPipelineJob(repo.name) {
        displayName(repo.displayName ?: repo.name)
        description('Generated by seed-job from jenkins/seed/repos.yaml. Edit the YAML, not this job: manual changes are overwritten.')

        branchSources {
            branchSource {
                source {
                    if (scm.type == 'github') {
                        github {
                            id("${repo.name}-github")          // stable ID keeps build history across re-seeds
                            repoOwner(scm.owner)
                            repository(scm.repository)
                            repositoryUrl("https://github.com/${scm.owner}/${scm.repository}")
                            configuredByUrl(false)
                            credentialsId(scm.credentialsId)
                            traits {
                                // 1 = skip branches that are also open PRs (avoids double builds)
                                gitHubBranchDiscovery { strategyId(1) }
                                // PRs from the same repo, built merged with their target branch.
                                // Fork PRs are NOT discovered: untrusted code must not run with our credentials.
                                gitHubPullRequestDiscovery { strategyId(1) }
                                headWildcardFilter {
                                    includes(branchFilter)
                                    excludes('')
                                }
                            }
                        }
                    } else {
                        git {
                            id("${repo.name}-git")
                            remote(scm.remote)
                            credentialsId(scm.credentialsId ?: '')
                            traits {
                                gitBranchDiscovery()
                                headWildcardFilter {
                                    includes(branchFilter)
                                    excludes('')
                                }
                            }
                        }
                    }
                }
            }
        }

        factory {
            workflowBranchProjectFactory {
                scriptPath(repo.jenkinsfile ?: 'Jenkinsfile')
            }
        }

        // Fallback if a webhook is missed: re-scan branches once a day.
        // (Each branch's Jenkinsfile also has a pollSCM fallback for new commits.)
        triggers {
            periodicFolderTrigger {
                interval('1d')
            }
        }

        // Keep jobs for deleted branches for a while, then clean them up.
        orphanedItemStrategy {
            discardOldItems {
                daysToKeep(7)
                numToKeep(10)
            }
        }

        // Central config for standardPipeline (deploy targets, branch rules, approvers).
        properties {
            folderProperties {
                properties {
                    stringProperty {
                        key('PIPELINE_CONFIG')
                        value(pipelineConfig)
                    }
                }
            }
        }
    }
}
